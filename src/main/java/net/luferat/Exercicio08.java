/**
 * Exercício 08) Loop com while
 *
 * Crie um programa que use while para imprimir os números pares de 2 até 20.
 */

package net.luferat;

public class Exercicio08 {

    public static void main(String[] args) {

        int i = 2;

        while(i <= 20) {
            System.out.println(i);
            i = i + 2;
        }

    }
}
