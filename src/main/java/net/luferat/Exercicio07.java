/**
 * Exercício 07) Loop com for
 *
 * Escreva um programa que use um for para imprimir os números de 1 a 10 (cada
 * número em sua linha).
 */

package net.luferat;

public class Exercicio07 {

    public static void main(String[] args) {

        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }

    }

}
